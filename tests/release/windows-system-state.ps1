# windows-system-state.ps1: snapshot, restore, and verify the machine integration
# that `testd doctor --fix` changes on Windows.
#
# Actions:
#   Snapshot  Record the NRPT rules for .<Tld> and the machine-root certificates
#             named "testd root". Changes nothing, but needs elevation so a
#             partial read cannot become a manifest that removes unseen rules.
#   Restore   Remove what the suite added, put back what it removed, then verify.
#   Verify    Compare the machine against the snapshot; throw on any difference.
#
# Every rule and certificate is name-scoped (.testdcheck and the testd root name),
# so nothing outside the throwaway TLD or the testd name is touched.

[CmdletBinding()]
param(
	[Parameter(Mandatory = $true)]
	[ValidateSet('Snapshot', 'Restore', 'Verify')]
	[string]$Action,

	[Parameter(Mandatory = $true)]
	[string]$Destination,

	[string]$Tld = 'testdcheck'
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
# Nothing here has an operator to answer a prompt, so never ask: a confirmation
# read on a redirected stdin stalls the run.
$ConfirmPreference = 'None'
# The runner captures this script through pipes and decodes UTF-8, as do the
# native tools whose output the checks read.
. "$PSScriptRoot\utf8-output.ps1"

if ($Tld -notmatch '^[a-z0-9]{1,10}$') { throw "invalid TLD" }
$Namespace = '.' + $Tld
$RootName = 'CN=testd root'
$NrptFile = Join-Path $Destination 'nrpt.json'
$RootDirectory = Join-Path $Destination 'roots'
# Add-DnsClientNrptRule switches that carry a snapshot property, split by type.
# Anything else a pre-existing rule sets is reported instead of silently dropped.
$FlagProperties = @(
	'DnssecValidationRequired', 'DnssecEnableAutoDnssec', 'DnssecQueryIPsecEncryption',
	'DnssecQueryIPsecRequired', 'DnssecNsec3',
	'DirectAccessQueryIPsecEncryption', 'DirectAccessQueryIPsecRequired'
)
$ValueProperties = @(
	'DisplayName', 'Comment', 'NameEncoding',
	'DirectAccessDnsServers', 'DirectAccessProxyName', 'DirectAccessProxyType'
)
$RuleProperties = $FlagProperties + $ValueProperties
# Rule properties that are either structural or regenerated by Windows.
$GeneratedProperties = @('Name', 'Version', 'Namespace', 'NameServers')

function Assert-Administrator {
	$identity = [Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
	if (-not $identity.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
		throw 'Reading or restoring NRPT rules and machine trust needs an elevated shell'
	}
}

function Get-NamespaceRules {
	$rules = Get-DnsClientNrptRule -ErrorAction Stop
	@($rules | Where-Object { $_.Namespace -eq $Namespace })
}

function Get-RootCertificates {
	# The Cert: provider drive only exists once Microsoft.PowerShell.Security is
	# loaded, which -Command does not guarantee, so read the store directly.
	$name = [System.Security.Cryptography.X509Certificates.StoreName]::Root
	$location = [System.Security.Cryptography.X509Certificates.StoreLocation]::LocalMachine
	$store = [System.Security.Cryptography.X509Certificates.X509Store]::new($name, $location)
	$store.Open([System.Security.Cryptography.X509Certificates.OpenFlags]::ReadOnly)
	try {
		@($store.Certificates | Where-Object { $_.Subject -eq $RootName })
	} finally {
		$store.Close()
	}
}

function Get-RootThumbprints {
	@(Get-RootCertificates | ForEach-Object { $_.Thumbprint.ToUpperInvariant() })
}

function Get-RuleSignature($rule) {
	[pscustomobject]@{
		Namespace = $rule.Namespace
		NameServers = (@($rule.NameServers | ForEach-Object { $_.ToString() }) -join ',')
		DisplayName = "$($rule.DisplayName)"
		Comment = "$($rule.Comment)"
	}
}

function Get-RuleProperties($rule) {
	# Keep every property, unsplit and unformatted, so a restore reproduces it.
	$properties = [ordered]@{}
	foreach ($property in $rule.PSObject.Properties) {
		$properties[$property.Name] = $property.Value
	}
	$properties
}

function Save-Snapshot {
	# Snapshotting needs the same access as restoring, so a partial read can never
	# become a manifest that removes rules it never saw.
	Assert-Administrator
	$rules = @(Get-NamespaceRules | ForEach-Object {
		[pscustomobject]@{
			Signature = Get-RuleSignature $_
			Properties = Get-RuleProperties $_
		}
	})
	# PowerShell 5.1 writes nothing for an empty array, so spell empty out.
	$json = if ($rules.Count -eq 0) { '[]' } else { ConvertTo-Json -InputObject $rules -Depth 10 }
	Set-Content -LiteralPath $NrptFile -Value $json -Encoding utf8
	New-Item -ItemType Directory -Path $RootDirectory -Force | Out-Null
	foreach ($root in Get-RootCertificates) {
		[IO.File]::WriteAllBytes((Join-Path $RootDirectory ($root.Thumbprint + '.cer')),
			$root.Export([Security.Cryptography.X509Certificates.X509ContentType]::Cert))
	}
	Write-Host "Saved system snapshot: $Destination"
}

function Read-Snapshot {
	if (-not (Test-Path -LiteralPath $NrptFile)) { throw "missing snapshot: $NrptFile" }
	$text = Get-Content -LiteralPath $NrptFile -Raw -Encoding utf8
	$rules = @()
	if ($text -and $text.Trim()) {
		$rules = @($text | ConvertFrom-Json | Where-Object { $null -ne $_ })
	}
	$certificates = @()
	if (Test-Path -LiteralPath $RootDirectory) {
		$certificates = @(Get-ChildItem -LiteralPath $RootDirectory -Filter *.cer)
	}
	[pscustomobject]@{ Rules = $rules; Certificates = $certificates }
}

function Add-SnapshotRule($rule) {
	$splat = @{
		Namespace = $rule.Signature.Namespace
		NameServers = @($rule.Signature.NameServers -split ',')
	}
	foreach ($name in $FlagProperties) {
		$property = $rule.Properties.PSObject.Properties[$name]
		if ($property -and $property.Value) { $splat[$name] = $true }
	}
	foreach ($name in $ValueProperties) {
		$property = $rule.Properties.PSObject.Properties[$name]
		if ($property -and -not [string]::IsNullOrEmpty("$($property.Value)")) {
			$splat[$name] = $property.Value
		}
	}
	Add-DnsClientNrptRule @splat | Out-Null
}

function Restore-Snapshot {
	Assert-Administrator
	$snapshot = Read-Snapshot
	foreach ($rule in Get-NamespaceRules) {
		Remove-DnsClientNrptRule -Name $rule.Name -Confirm:$false -ErrorAction SilentlyContinue
	}
	foreach ($rule in $snapshot.Rules) { Add-SnapshotRule $rule }
	$expected = @($snapshot.Certificates | ForEach-Object { $_.BaseName.ToUpperInvariant() })
	foreach ($thumbprint in Get-RootThumbprints) {
		if ($expected -notcontains $thumbprint) {
			& certutil.exe -delstore -f Root $thumbprint | Out-Null
			if ($LASTEXITCODE -ne 0) { throw "certutil -delstore failed for $thumbprint" }
		}
	}
	$current = @(Get-RootThumbprints)
	foreach ($certificate in $snapshot.Certificates) {
		if ($current -notcontains $certificate.BaseName.ToUpperInvariant()) {
			& certutil.exe -addstore -f Root $certificate.FullName | Out-Null
			if ($LASTEXITCODE -ne 0) { throw "certutil -addstore failed for $($certificate.Name)" }
		}
	}
}

function Get-PropertyDifferences($snapshot) {
	$differences = @()
	# A function that returns nothing leaves $null, and StrictMode rejects
	# $null.Count, so keep the rule set an array.
	$restored = @(Get-NamespaceRules)
	$expected = @($snapshot.Rules)
	if ($restored.Count -ne $expected.Count) {
		return @("NRPT rules for ${Namespace}: expected $($expected.Count), found $($restored.Count)")
	}
	$actual = @($restored | ForEach-Object { Get-RuleSignature $_ })
	foreach ($rule in $expected) {
		$signature = $rule.Signature
		$match = $actual | Where-Object {
			$_.Namespace -eq $signature.Namespace -and $_.NameServers -eq $signature.NameServers -and
			$_.DisplayName -eq $signature.DisplayName -and $_.Comment -eq $signature.Comment
		}
		if (-not $match) {
			$differences += "NRPT rule for $Namespace did not come back: $($signature | ConvertTo-Json -Compress)"
			continue
		}
		$unsupported = @($rule.Properties.PSObject.Properties | Where-Object {
			$RuleProperties -notcontains $_.Name -and $GeneratedProperties -notcontains $_.Name -and
			$null -ne $_.Value -and "$($_.Value)" -ne ''
		} | ForEach-Object { $_.Name })
		if ($unsupported) {
			$differences += "NRPT rule for $Namespace was recreated without: $($unsupported -join ', ')"
		}
	}
	$differences
}

function Test-Snapshot {
	Assert-Administrator
	$snapshot = Read-Snapshot
	$differences = @(Get-PropertyDifferences $snapshot)
	$expected = @($snapshot.Certificates | ForEach-Object { $_.BaseName.ToUpperInvariant() })
	$actual = @(Get-RootThumbprints)
	foreach ($thumbprint in $expected) {
		if ($actual -notcontains $thumbprint) { $differences += "testd root $thumbprint is missing from the machine store" }
	}
	foreach ($thumbprint in $actual) {
		if ($expected -notcontains $thumbprint) { $differences += "testd root $thumbprint was left in the machine store" }
	}
	if ($differences.Count -gt 0) { throw ($differences -join '; ') }
}

switch ($Action) {
	'Snapshot' { Save-Snapshot }
	'Restore' { Restore-Snapshot; Test-Snapshot }
	'Verify' { Test-Snapshot }
}
